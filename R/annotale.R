#' Runs the "predict" and "analyze" steps of AnnoTALE on a fasta file
#'
#' An R wrapper around the
#' \href{https://doi.org/10.1038/srep21077}{AnnoTALE} 'AnnoTALE.jar
#' predict' and 'AnnoTALE.jar analyze' shell calls. The whole AnnoTALE workflow
#' can be completed by a subsequent call to the \code{\link{run_annotale_build}}
#' function.
#'
#' @param fasta_file Path to a fasta file containing DNA sequences (e.g. a
#'   genome assembly) to be analyzed for TALE content.
#' @param output_dir Directory where output will be written, created if it
#'   does not exist. The default is a new directory under [tempdir()], which
#'   R deletes when the session ends: give a path to keep the results.
#' @param prefix A scalar character vector containing a prefix that will be
#'   appended to TALE names by AnnoTALE. If not supplied, the function will try
#'   to guess the prefix from the input file name.
#' @param opt_param A single string of options for the predict stage, as
#'   \code{key=value} pairs separated by spaces. AnnoTALE predict has one:
#'   \code{Sensitive}, \code{false} by default; \code{"Sensitive=true"}
#'   runs its sensitive scan. The keys this function sets itself
#'   (\code{g}, \code{s}, \code{outdir}) are refused: use
#'   \code{fasta_file}, \code{prefix} and \code{output_dir}. The analyze
#'   stage has no option of its own beyond a run name.
#' @param java_args A single string of options for the Java virtual
#'   machine, placed before \code{-jar} in both stages, such as
#'   \code{"-Xmx8G"} to raise its memory limit. The default, \code{""},
#'   leaves Java's own defaults.
#' @param annotale_jar Path to the AnnoTALE jar file. The default is the
#'   copy [tantale_setup()] downloads; give a path to use another version.
#' @return \code{output_dir}, invisibly, so that the call can be passed
#'   straight to [tales_from_annotale()]. If either stage exits with a
#'   non-zero status, the
#'   function stops with an error of class
#'   \code{tantale_error_annotale_failed}.
#' @export
#' @family external TALE tools
#' @examples
#' \donttest{
#' # Needs a Java runtime, and the tools and genomes tantale_setup() downloads.
#' fasta <- tantale_genome("MAI1")
#' out <- file.path(tempdir(), "annotale_predict_example")
#' run_annotale_predict(fasta, output_dir = out)
#' list.files(file.path(out, "Predict"))
#' }
run_annotale_predict <- function(fasta_file,
                            output_dir = tempfile("annotale_predict_"),
                            prefix = NULL,
                            opt_param = "Sensitive=false",
                            java_args = "",
                            annotale_jar = .tantale_tool("annotale")
                            ) {
  .check_jar_args(opt_param, java_args,
                  reserved = c(g = "fasta_file", s = "prefix", outdir = "output_dir"),
                  fn = "run_annotale_predict")
  # Define output dirs for the various stages of AnnoTALE
  stopifnot(dir.exists(output_dir) || dir.create(path = output_dir, showWarnings = TRUE, recursive = TRUE, mode = "775"))
  predict_dir <- file.path(output_dir, "Predict")
  analyze_dir <- file.path(output_dir, "Analyze")
  # Define a prefix for TALEs (the strain or assembly ID) derived from the genome file name.
  if( is.null(prefix) ) {
  prefix <- gsub(pattern = "^(.*)\\.(fasta|fa|fas)$" , replacement  = "\\1", basename(fasta_file), perl = TRUE)
  }
  # Run the "predict" stage of AnnoTALE
  comPredict <- paste0(
    "java ", java_args, " -jar ", shQuote(annotale_jar),
    " predict ", opt_param,
    " g=", shQuote(fasta_file),
    " s=", shQuote(prefix),
    " outdir=", shQuote(predict_dir)
  )
  cli::cli_inform(c("Running AnnoTALE predict for {.val {prefix}}", " " = "{comPredict}"))
  .annotale_exec(comPredict, "predict")

  # Run the "analyze" stage of AnnoTALE
  comAnalyze <- paste0(
    "java ", java_args, " -jar ", shQuote(annotale_jar),
    " analyze ",
    " t=", shQuote(list.files(predict_dir, pattern = "^TALE_DNA_sequences_", full.names = TRUE)),
    " outdir=", shQuote(analyze_dir)
  )
  cli::cli_inform(c("Running AnnoTALE analyze for {.val {prefix}}", " " = "{comAnalyze}"))
  .annotale_exec(comAnalyze, "analyze")
  invisible(output_dir)
}






#' Run the "build" stage of AnnoTALE
#'
#' An R wrapper around the \href{https://doi.org/10.1038/srep21077}{AnnoTALE} 'AnnoTALE.jar build' program.
#' It usually takes its input from the file generated by the \code{\link{run_annotale_predict}}
#' function.
#'
#' @param fasta_file Path to a \code{TALE_DNA_sequences_*} fasta file, as
#'   written by \code{\link{run_annotale_predict}}'s "predict" stage, to be
#'   classified into groups.
#' @param output_dir Directory where output will be written, created if it
#'   does not exist. The default is a new directory under [tempdir()], which
#'   R deletes when the session ends: give a path to keep the results.
#' @param opt_param A single string of options for AnnoTALE build, as
#'   \code{key=value} pairs separated by spaces. The default writes out the
#'   tool's own defaults: \code{c}, the cutoff on the distance that defines
#'   the maximum extent of a TALE class (5), and \code{s}, the significance
#'   level on the alignment p-value (0.01). An option left out of a string
#'   of your own keeps its default. The keys this function sets itself
#'   (\code{t}, \code{outdir}) are refused: use \code{fasta_file} and
#'   \code{output_dir}.
#' @param java_args A single string of options for the Java virtual
#'   machine, placed before \code{-jar}. The default starts Java with 512
#'   MB of memory and lets it grow to 6 GB; raise \code{-Xmx} if build runs
#'   out of memory.
#' @param annotale_jar Path to the AnnoTALE jar file. The default is the
#'   copy [tantale_setup()] downloads; give a path to use another version.
#' @return \code{output_dir}, invisibly. If AnnoTALE exits with a non-zero
#'   status, the
#'   function stops with an error of class
#'   \code{tantale_error_annotale_failed}.
#' @export
#' @family external TALE tools
#' @examples
#' \donttest{
#' # Needs a Java runtime and the tools tantale_setup() downloads. Chained
#' # from run_annotale_predict()'s own output, since that is the file build
#' # normally classifies.
#' fasta <- tantale_genome("MAI1")
#' predict_out <- file.path(tempdir(), "annotale_build_example", "predict")
#' run_annotale_predict(fasta, output_dir = predict_out)
#' predicted <- list.files(file.path(predict_out, "Predict"),
#'                         pattern = "^TALE_DNA_sequences_", full.names = TRUE)
#' build_out <- file.path(tempdir(), "annotale_build_example", "build")
#' run_annotale_build(predicted, output_dir = build_out)
#' list.files(build_out)
#' }
run_annotale_build <- function(fasta_file,
                          output_dir = tempfile("annotale_build_"),
                          opt_param = "c=5 s=0.01",
                          java_args = "-Xms512M -Xmx6G",
                          annotale_jar = .tantale_tool("annotale")
                          ) {
  .check_jar_args(opt_param, java_args,
                  reserved = c(t = "fasta_file", outdir = "output_dir"),
                  fn = "run_annotale_build")
  if(! dir.exists(output_dir)) dir.create(path = output_dir, showWarnings = TRUE, recursive = TRUE, mode = "775")
  comBuild <- paste0(
    "java ", java_args, " -jar ", shQuote(annotale_jar),
    " build ", opt_param,
    " t=", shQuote(fasta_file),
    " outdir=", shQuote(output_dir)
  )
  cli::cli_inform(c("Running AnnoTALE build", " " = "{comBuild}"))
  .annotale_exec(comBuild, "build")
  invisible(output_dir)
}


#' Run one AnnoTALE stage and stop if it fails
#'
#' AnnoTALE's jar is run with the system Java, outside the conda
#' environment, so it goes through \code{.tantale_exec()} for the exit
#' status check and then raises AnnoTALE's own condition class.
#'
#' @param command The shell command.
#' @param stage The AnnoTALE stage, for the message ("predict", "analyze",
#'   "build").
#' @param quiet If \code{TRUE}, discard AnnoTALE's standard output and keep
#'   its standard error for the error message; if \code{FALSE}, both reach
#'   the console as they are written.
#' @return \code{0}, invisibly.
#' @noRd
.annotale_exec <- function(command, stage, quiet = FALSE) {
  errFile <- NULL
  if (quiet) {
    errFile <- tempfile("annotale_stderr")
    on.exit(unlink(errFile), add = TRUE)
    command <- paste(command, "> /dev/null")
  }
  status <- .tantale_exec(command, stderr_file = errFile, check = FALSE)
  if (!identical(as.integer(status), 0L)) {
    saidWhy <- if (!is.null(errFile) && file.exists(errFile)) {
      utils::tail(readLines(errFile, warn = FALSE), 5)
    } else character()
    # AnnoTALE's text is shown verbatim, braces included.
    saidWhy <- gsub("}", "}}", gsub("{", "{{", saidWhy, fixed = TRUE), fixed = TRUE)
    cli::cli_abort(
      c("AnnoTALE {stage} failed with exit status {status}.",
        if (length(saidWhy)) c("i" = "It said:"),
        stats::setNames(saidWhy, rep(" ", length(saidWhy)))),
      class = c("tantale_error_annotale_failed", "tantale_error"))
  }
  invisible(0L)
}


#' Check the strings a jar wrapper passes to Java and to the tool
#'
#' The Jstacs tools (AnnoTALE, PrediTALE) read \code{key=value} pairs and,
#' given a key twice, silently keep the last: PrediTALE given two
#' \code{outdir=} wrote to the second and left the first empty (ledger
#' §51). The wrappers put \code{opt_param} before their own keys, so a key
#' the wrapper also sets would be ignored without a word; refused here
#' instead, naming the argument to use.
#'
#' @param opt_param,java_args The two strings; \code{NULL} for a wrapper
#'   without that argument.
#' @param reserved The keys the wrapper sets itself, named by key, each
#'   value the R argument that supplies it.
#' @param fn The wrapper's name, for the message.
#' @return \code{NULL}, invisibly.
#' @noRd
.check_jar_args <- function(opt_param, java_args, reserved = character(), fn) {
  args <- list(opt_param = opt_param, java_args = java_args)
  for (a in names(args)) {
    v <- args[[a]]
    if (!is.null(v) && !(is.character(v) && length(v) == 1L && !is.na(v))) {
      cli::cli_abort("{.arg {a}} of {.fn {fn}} must be a single string.",
                     class = c("tantale_error_jar_args", "tantale_error"))
    }
  }
  if (is.null(opt_param)) return(invisible(NULL))
  # A key starts the string or follows a space, and is followed by "=";
  # words inside a quoted value such as Strand="forward strand" are not.
  keys <- regmatches(opt_param,
                     gregexpr("(?<!\\S)[A-Za-z]+(?==)", opt_param, perl = TRUE))[[1]]
  taken <- intersect(keys, names(reserved))
  if (length(taken)) {
    cli::cli_abort(
      c("{.arg opt_param} sets {.code {paste0(taken, '=')}}, which {.fn {fn}} sets itself.",
        "i" = "Use {.arg {unname(reserved[taken])}} instead."),
      class = c("tantale_error_jar_args", "tantale_error"))
  }
  invisible(NULL)
}


#' Download AnnoTALE's catalogue of TALE classes
#'
#' A TALE class groups the TALEs of different strains that are similar
#' enough to be considered the same effector, and carries the systematic
#' name the literature uses for it (\code{TalAA}, \code{TalAB}, ...).
#' AnnoTALE curates that catalogue and publishes it; this is an R wrapper
#' around its 'AnnoTALEcli.jar loadAndView' call, which downloads the
#' current definition. \code{\link{run_annotale_assign}} consumes what it
#' writes.
#'
#' @details
#' The download is slow and bulky: about a quarter of an hour, and some
#' 440 MB of output, most of it the class builder itself, which carries a
#' cached alignment between every pair of catalogued TALEs. The file is
#' therefore kept once and reused rather than fetched per call, which is
#' what \code{output_dir} is for: point it at a directory you keep, and
#' pass the returned path to \code{\link{run_annotale_assign}} as often as
#' you like.
#'
#' Record the date along with any class you take from it. A class name is
#' stable, but the catalogue grows, and the index AnnoTALE appends to the
#' class when it names a TALE (\code{TalAH30}, the thirtieth member of
#' \code{TalAH}) is only true of the catalogue that produced it.
#'
#' @param output_dir Directory where the catalogue will be written, created
#'   if it does not exist. The default is a new directory under
#'   [tempdir()], which R deletes when the session ends: given how long the
#'   download takes, give a path you keep.
#' @param class_builder Path to a class builder XML to read instead of
#'   downloading, as written by an earlier call. \code{NULL}, the default,
#'   downloads the current definition.
#' @param opt_param A single string of further options for the tool, as
#'   \code{key=value} pairs separated by spaces. The keys this function
#'   sets itself (\code{c}, \code{cb}, \code{outdir}) are refused: use
#'   \code{class_builder} and \code{output_dir}.
#' @param java_args A single string of options for the Java virtual
#'   machine, placed before \code{-jar}. The default raises the heap to 8
#'   GB, which the catalogue needs; rebuilding it was seen to hold 1.8 GB
#'   resident.
#' @param annotale_jar Path to the AnnoTALE jar file. The default is the
#'   copy [tantale_setup()] downloads; give a path to use another version.
#' @return The path of the class builder XML, invisibly, so the call can be
#'   passed straight to \code{\link{run_annotale_assign}}. Beside it,
#'   \code{output_dir} also holds \code{Lists_of_classes,_strains_and_TALEs/},
#'   whose \code{List_of_classes.txt} gives every class as plain text, one
#'   line per member with its aligned repeat-variable diresidues, strain
#'   and systematic name. That file answers "which class is this TALE in"
#'   without going through \code{\link{run_annotale_assign}} at all, when
#'   the TALE is already catalogued.
#' @export
#' @family external TALE tools
#' @seealso \code{\link{run_annotale_assign}}, which places TALEs into
#'   these classes.
#' @examplesIf interactive()
#' # Slow: downloads and rebuilds the catalogue, about 15 minutes.
#' classes <- run_annotale_load_classes(output_dir = tempfile("annotale_classes_"))
run_annotale_load_classes <- function(output_dir = tempfile("annotale_classes_"),
                                      class_builder = NULL,
                                      opt_param = "",
                                      java_args = "-Xms512M -Xmx8G",
                                      annotale_jar = .tantale_tool("annotale")) {
  .check_jar_args(opt_param, java_args,
                  reserved = c(c = "class_builder", cb = "class_builder",
                               outdir = "output_dir"),
                  fn = "run_annotale_load_classes")
  stopifnot(dir.exists(output_dir) ||
              dir.create(output_dir, showWarnings = TRUE, recursive = TRUE))
  source <- if (is.null(class_builder)) {
    "c=\"Download current definition\""
  } else {
    if (!file.exists(class_builder)) {
      cli::cli_abort("No class builder at {.file {class_builder}}.",
                     class = c("tantale_error_missing_file", "tantale_error"))
    }
    paste0("c=\"Load from local file\" cb=", shQuote(class_builder))
  }
  command <- paste0(
    "java ", java_args, " -jar ", shQuote(annotale_jar),
    " loadAndView ", opt_param, " ", source,
    " outdir=", shQuote(output_dir)
  )
  cli::cli_inform(c(
    "Loading AnnoTALE's TALE classes",
    if (is.null(class_builder)) c("i" = "Downloading the current definition; this takes several minutes."),
    " " = "{command}"))
  .annotale_exec(command, "loadAndView")

  built <- list.files(output_dir, pattern = "^Class_builder.*\\.xml$",
                      full.names = TRUE)
  if (length(built) == 0L) {
    cli::cli_abort(
      c("{.fn run_annotale_load_classes} wrote no class builder to {.file {output_dir}}.",
        "i" = "AnnoTALE reported no error, so this is unexpected."),
      class = c("tantale_error_annotale_failed", "tantale_error"))
  }
  invisible(built[[1L]])
}


#' Assign TALEs to AnnoTALE's published classes
#'
#' An R wrapper around the 'AnnoTALEcli.jar assign' call. Each TALE given
#' is placed in the class of the catalogue it belongs to, and any that fit
#' none open a new class. Where
#' \code{\link{run_annotale_build}} groups the TALEs you hand it among
#' themselves, knowing nothing of what the rest of the world calls them,
#' this one answers "which published class is this TALE in", so its names
#' can be compared with the literature's.
#'
#' @param fasta_file Path to the TALEs to assign: DNA or protein sequences,
#'   RVD sequences, or the \code{TALE DNA parts}/\code{TALE Protein parts}
#'   written by \code{\link{run_annotale_predict}}'s analyze stage.
#' @param class_builder Path to the class builder XML holding the classes
#'   to assign against, as \code{\link{run_annotale_load_classes}} returns.
#' @param output_dir Directory where output will be written, created if it
#'   does not exist. The default is a new directory under [tempdir()],
#'   which R deletes when the session ends: give a path to keep the results.
#' @param strain The strain the TALEs come from. AnnoTALE uses it to build
#'   the systematic names it proposes, so without it they are unnamed.
#' @param accession The genome's accession number, recorded in the report.
#' @param opt_param A single string of further options, as \code{key=value}
#'   pairs separated by spaces. The keys this function sets itself
#'   (\code{t}, \code{c}, \code{s}, \code{a}, \code{outdir}) are refused:
#'   use \code{fasta_file}, \code{class_builder}, \code{strain},
#'   \code{accession} and \code{output_dir}.
#' @param java_args A single string of options for the Java virtual
#'   machine, placed before \code{-jar}. The default raises the heap to 8
#'   GB, which reading the catalogue needs.
#' @param annotale_jar Path to the AnnoTALE jar file. The default is the
#'   copy [tantale_setup()] downloads; give a path to use another version.
#' @return \code{output_dir}, invisibly. It holds the per-TALE assignment
#'   report, a table of original against proposed systematic names, a
#'   report and figure for each class that changed or was created, and a
#'   class builder extended with the TALEs given.
#' @export
#' @family external TALE tools
#' @seealso \code{\link{run_annotale_load_classes}}, which fetches the
#'   classes; \code{\link{run_annotale_build}}, which builds classes from
#'   scratch instead.
#' @examplesIf interactive()
#' # Needs a Java runtime and the catalogue, which takes a while to fetch.
#' classes <- run_annotale_load_classes(output_dir = tempfile("annotale_classes_"))
#' predicted <- run_annotale_predict(tantale_genome("MAI1"))
#' tales <- list.files(file.path(predicted, "Predict"),
#'                     pattern = "^TALE_DNA_sequences_", full.names = TRUE)
#' run_annotale_assign(tales, class_builder = classes, strain = "MAI1")
run_annotale_assign <- function(fasta_file,
                                class_builder,
                                output_dir = tempfile("annotale_assign_"),
                                strain = NULL,
                                accession = NULL,
                                opt_param = "",
                                java_args = "-Xms512M -Xmx8G",
                                annotale_jar = .tantale_tool("annotale")) {
  .check_jar_args(opt_param, java_args,
                  reserved = c(t = "fasta_file", c = "class_builder",
                               s = "strain", a = "accession",
                               outdir = "output_dir"),
                  fn = "run_annotale_assign")
  for (f in c(fasta_file = fasta_file, class_builder = class_builder)) {
    if (!file.exists(f)) {
      cli::cli_abort("No file at {.file {f}}.",
                     class = c("tantale_error_missing_file", "tantale_error"))
    }
  }
  stopifnot(dir.exists(output_dir) ||
              dir.create(output_dir, showWarnings = TRUE, recursive = TRUE))
  command <- paste0(
    "java ", java_args, " -jar ", shQuote(annotale_jar),
    " assign ", opt_param,
    " t=", shQuote(fasta_file),
    " c=", shQuote(class_builder),
    if (!is.null(strain)) paste0(" s=", shQuote(strain)),
    if (!is.null(accession)) paste0(" a=", shQuote(accession)),
    " outdir=", shQuote(output_dir)
  )
  cli::cli_inform(c("Assigning TALEs to AnnoTALE classes", " " = "{command}"))
  .annotale_exec(command, "assign")
  invisible(output_dir)
}
